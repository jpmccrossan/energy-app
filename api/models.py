from django.db import models

class EnergyData(models.Model):
    date_time = models.DateTimeField()
    net_demand = models.IntegerField()
    total_system_demand = models.IntegerField()
    england_wales_demand = models.IntegerField()
    generation = models.IntegerField()
    gas = models.IntegerField()
    coal = models.IntegerField()
    nuclear = models.IntegerField()
    scot_wind = models.FloatField()
    eng_wind = models.FloatField()
    uk_wind = models.IntegerField()
    wind_capacity = models.IntegerField()
    hydro = models.IntegerField()
    imports = models.IntegerField()
    ifa_flow = models.IntegerField()
    ifa2_flow = models.IntegerField()
    britned_flow = models.IntegerField()
    moyle_flow = models.IntegerField()
    east_west_flow = models.IntegerField()
    nemo_flow = models.IntegerField()
    nsl_flow = models.IntegerField()
    eleclink_flow = models.IntegerField()
    net_interc_flow = models.IntegerField()
    biomass = models.IntegerField()
    other = models.IntegerField()
    solar = models.IntegerField()
    solar_cap = models.IntegerField()
    pumped_storage = models.IntegerField()
    storage = models.IntegerField()
    carbon_intensity = models.IntegerField()
    low_carbon = models.IntegerField()
    zero_carbon = models.IntegerField()
    renewable = models.IntegerField()
    fossil = models.IntegerField()
    gas_perc = models.FloatField()
    coal_perc = models.FloatField()
    nuclear_perc = models.FloatField()
    wind_perc = models.FloatField()
    hydro_perc = models.FloatField()
    imports_perc = models.FloatField()
    biomass_perc = models.FloatField()
    other_perc = models.FloatField()
    solar_perc = models.FloatField()
    storage_perc = models.FloatField()
    generation_perc = models.IntegerField()
    low_carbon_perc = models.FloatField()
    zero_carbon_perc = models.FloatField()
    renewable_perc = models.FloatField()
    fossil_perc = models.FloatField()

    def __str__(self):
        return str(self.date_time)